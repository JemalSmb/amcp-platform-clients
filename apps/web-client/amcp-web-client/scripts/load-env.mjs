// Writes src/app/core/env.generated.ts from .env (or process env).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
const fileVars = {};
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) fileVars[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}
const get = (k, d = '') => process.env[k] ?? fileVars[k] ?? d;

const KEYS = [["apiBaseUrl", "API_BASE_URL"], ["gatewayBaseUrl", "GATEWAY_BASE_URL"], ["supabaseUrl", "SUPABASE_URL"], ["supabaseAnonKey", "SUPABASE_ANON_KEY"]];
const env = Object.fromEntries(KEYS.map(([name, key]) => [name, get(key)]));

const missing = KEYS.filter(([, key]) => !get(key)).map(([, key]) => key);
if (missing.length) {
  console.warn(`[env] missing in .env / environment: ${missing.join(', ')}`);
}

const out = `// Generated by scripts/load-env.mjs from .env -- do not edit or commit.
export const env = ${JSON.stringify(env, null, 2)};
`;
writeFileSync(resolve(root, 'src/app/core/env.generated.ts'), out);
